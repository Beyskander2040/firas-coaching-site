import Link from "next/link";
import { ReactNode } from "react";

type Variant = "primary" | "secondary" | "ghost";

const base =
  "inline-flex items-center justify-center gap-2 rounded-full px-6 py-3 text-sm font-semibold tracking-wide transition-all duration-300 hover:scale-[1.03] hover:shadow-lg active:scale-[0.97]";

const variants: Record<Variant, string> = {
  primary: "bg-accent text-accent-foreground shadow-accent/20 hover:bg-accent/90",
  secondary:
    "border border-border-subtle text-foreground hover:border-accent/50 hover:bg-surface",
  ghost: "text-foreground hover:text-accent",
};

export default function Button({
  href,
  variant = "primary",
  children,
  className = "",
  external = false,
}: {
  href: string;
  variant?: Variant;
  children: ReactNode;
  className?: string;
  external?: boolean;
}) {
  const classes = `${base} ${variants[variant]} ${className}`;

  if (external) {
    return (
      <a href={href} target="_blank" rel="noopener noreferrer" className={classes}>
        {children}
      </a>
    );
  }

  return (
    <Link href={href} className={classes}>
      {children}
    </Link>
  );
}
